// ✅ Helper: Get blog post by slug
export function getBlogPostBySlug(slug: string): BlogPost | undefined {
  return blogPosts.find((post) => post.slug === slug);
}

// ✅ Helper: Get all slugs for static params
export function getAllBlogSlugs(): string[] {
  return blogPosts.map((post) => post.slug);
}

// ✅ Helper: Get related posts
export function getRelatedPosts(postId: string, limit = 3): BlogPost[] {
  const post = blogPosts.find((p) => p.id === postId);
  if (!post) return [];

  if (post.relatedPostIds && post.relatedPostIds.length > 0) {
    return post.relatedPostIds
      .slice(0, limit)
      .map((id) => blogPosts.find((p) => p.id === id))
      .filter(Boolean) as BlogPost[];
  }

  return blogPosts
    .filter((p) => p.id !== postId && p.category === post.category)
    .slice(0, limit);
}